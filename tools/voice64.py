#!/usr/bin/env python3
"""voice/*.wav -> src/data/voice.asm: 4-bit speech for the SID's volume.

The SID has no DAC, but its master volume ($d418, 4 bits) moves the output's
DC level: written ~5,500 times a second, the volume is the wave itself (the
classic C64 sample trick). On the 8580 the DC is small, so the voice routine
also keeps the three voices at a constant level (test bit, pulse, sustain 15)
for the volume to scale.

Two samples a byte, the first in the high nibble. For every phrase:
VOICE_<NAME> (an index), and the tables voice_lo/hi (address) and
voice_len_lo/hi (bytes).

  voice64.py src/data/voice.asm sugarbyte=voice/sugarbyte.wav ...
"""
import array
import subprocess
import sys

RATE = 5500
TARGET_RMS = 0.35


def load(path):
    """mono, RATE Hz, the band of speech, normalised to [-1, 1]"""
    raw = subprocess.run(
        ['ffmpeg', '-loglevel', 'error', '-i', path,
         '-af', f'highpass=f=150,lowpass=f={RATE // 2 - 200},acompressor=threshold=0.1:ratio=4',
         '-ac', '1', '-ar', str(RATE), '-f', 's16le', '-'],
        check=True, capture_output=True).stdout
    s = array.array('h', raw)
    s = [v / 32768.0 for v in s]
    rms = max(1e-4, (sum(v * v for v in s) / len(s)) ** 0.5)
    gain = TARGET_RMS / rms
    return [max(-1.0, min(1.0, v * gain)) for v in s]


def level(v):
    return max(0, min(15, round((v + 1) / 2 * 15)))


def main():
    out_asm, *items = sys.argv[1:]
    out = ["; GENERATED by tools/voice64.py - do not edit.", '', f"VOICE_RATE = {RATE}"]
    names, data = [], []
    for i, item in enumerate(items):
        name, path = item.split('=', 1)
        lv = [level(v) for v in load(path)]
        if len(lv) % 2:
            lv.append(lv[-1])
        b = [(lv[k] << 4) | lv[k + 1] for k in range(0, len(lv), 2)]
        names.append(name)
        data.append(b)
        out.append(f"VOICE_{name.upper()} = {i}             ; {len(lv) / RATE:.2f} s, {len(b)} bytes")
    out.append("voice_lo .byte " + ",".join(f"<voice_{n}" for n in names))
    out.append("voice_hi .byte " + ",".join(f">voice_{n}" for n in names))
    out.append("voice_len_lo .byte " + ",".join(f"<{len(d)}" for d in data))
    out.append("voice_len_hi .byte " + ",".join(f">{len(d)}" for d in data))
    for n, d in zip(names, data):
        out.append(f"voice_{n}")
        for k in range(0, len(d), 32):
            out.append("        .byte " + ",".join(f"${x:02x}" for x in d[k:k + 32]))
    open(out_asm, 'w').write('\n'.join(out) + '\n')
    print(f"voice: {sum(map(len, data))} bytes")


if __name__ == '__main__':
    main()
